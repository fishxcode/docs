/**
 * 按当前语言取文案并替换占位符。
 * 译文里没有的 key 直接回退简体中文原文；vars 中缺失的占位符原样保留。
 */
export function statusText(lang: Locale, source: string, vars?: StatusVars): string {
  const table = STATUS_TEXT[lang] ?? STATUS_TEXT[DEFAULT_LOCALE];
  const template = table[source] ?? source;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(vars, key) ? String(vars[key]) : match,
  );
}

/**
 * 厂商标签：品牌名各语言保持一致，只对 other 做本地化。
 * zh / zh-TW 直接沿用 FAMILY_LABELS 的值。
 */
export function statusFamilyLabel(lang: Locale, family: Family): string {
  if (family !== 'other' || HTML_LANG[lang].startsWith('zh')) {
    return FAMILY_LABELS[family];
  }
  return STATUS_TEXT[lang]['其他模型'] ?? FAMILY_LABELS.other;
}
